export function findCurriculumSubject(fileName: string, textSample: string = ""): CurriculumSubjectDef | null {
  const lowerFile = fileName.toLowerCase();
  const lowerText = textSample.slice(0, 4000).toLowerCase();

  // 1. First priority: Check exact or strong keyword match in file name
  for (const item of NCTB_CURRICULUM_DATABASE) {
    if (lowerFile.includes(item.subjectName.toLowerCase()) || (item.subjectBn && lowerFile.includes(item.subjectBn))) {
      return item;
    }
    for (const alias of item.aliases) {
      const a = alias.toLowerCase().trim();
      if (a.length <= 4) {
        const regex = new RegExp(`(^|[^a-z0-9])${a}([^a-z0-9]|$)`, "i");
        if (regex.test(lowerFile)) return item;
      } else {
        if (lowerFile.includes(a)) return item;
      }
    }
  }

  // 2. Second priority: Check textSample with word boundaries for short aliases
  for (const item of NCTB_CURRICULUM_DATABASE) {
    if (lowerText.includes(item.subjectName.toLowerCase()) || (item.subjectBn && lowerText.includes(item.subjectBn))) {
      return item;
    }
    for (const alias of item.aliases) {
      const a = alias.toLowerCase().trim();
      if (a.length <= 4) {
        const regex = new RegExp(`(^|[^a-z0-9\u0980-\u09FF])${a}([^a-z0-9\u0980-\u09FF]|$)`, "i");
        if (regex.test(lowerText)) return item;
      } else {
        if (lowerText.includes(a)) return item;
      }
    }
  }

  return null;
}

